// Run explicitly with: node --test tests/booking-flow.integration.js
// All fixtures and API writes share one transaction, rolled back in finally.
require('dotenv').config({ quiet: true });
const test = require('node:test');
const assert = require('node:assert/strict');
const pool = require('../src/db');
const { ensureBookingSchema, registerBookingRoutes } = require('../src/booking-routes');
test('deposit verification and owner-approved rescheduling with authorization and conflict checks', async () => {
  await ensureBookingSchema(pool);
  const db = await pool.getConnection();
  try {
    await db.beginTransaction();
    const insert = async (sql, args) => (await db.execute(sql, args))[0].insertId;
    const suffix = `${Date.now()}-${process.pid}`;
    const user = async role => insert('INSERT INTO users(full_name,email,password_hash,role) VALUES (?,?,?,?)', [`Booking test ${role}`,`${role}-${suffix}@example.invalid`,'test-fixture-no-login',role]);
    const owner = await user('owner'), customer = await user('customer');
    const salon = await insert("INSERT INTO salons(owner_id,name,address,city,opening_time,closing_time) VALUES (?,'Booking test salon','Test only','Nasugbu','09:00','18:00')",[owner]);
    const service = await insert("INSERT INTO services(salon_id,name,price,duration_minutes) VALUES (?,'Test haircut',1000,60)",[salon]);
    const handlers = new Map();
    const app = { post: (path, _auth, handler) => handlers.set(`POST ${path}`,handler), patch: (path,_auth,handler) => handlers.set(`PATCH ${path}`,handler) };
    const scoped = { execute: db.execute.bind(db), beginTransaction:async()=>{}, commit:async()=>{}, rollback:async()=>{}, release:()=>{} };
    registerBookingRoutes(app,{getConnection:async()=>scoped},()=>{});
    const call = async (key, role, sub, params, body) => {
      let status=200, payload;
      const res={status(value){status=value;return this;},json(value){payload=value;}};
      await handlers.get(key)({user:{role,sub},params,body},res,error=>{throw error;});
      return {status,...payload};
    };
    let result=await call('POST /api/bookings','customer',customer,{}, {serviceId:service,appointmentAt:'2099-01-01 09:00:00'});
    assert.equal(result.status,200);const id=result.data.id;
    assert.equal(Number(result.data.depositAmount),200);
    result=await call('PATCH /api/owner/bookings/:bookingId','owner',owner,{bookingId:id},{status:'confirmed'});
    assert.equal(result.status,409);
    result=await call('POST /api/bookings/:id/deposit','customer',customer,{id},{reference:'123',imageData:'invalid'});
    assert.equal(result.status,400);
    const receipt='data:image/png;base64,iVBORw0KGgoAAAANSUhEUgAAAAEAAAABCAQAAAC1HAwCAAAAC0lEQVR42mP8/x8AAwMCAO+jRZkAAAAASUVORK5CYII=';
    result=await call('POST /api/bookings/:id/deposit','customer',customer,{id},{reference:'1234567890123',imageData:receipt});
    assert.equal(result.status,200);
    result=await call('PATCH /api/owner/bookings/:id/deposit','owner',customer,{id},{status:'verified'});
    assert.equal(result.status,404);
    result=await call('PATCH /api/owner/bookings/:id/deposit','owner',owner,{id},{status:'verified'});
    assert.equal(result.status,200);
    result=await call('PATCH /api/owner/bookings/:bookingId','owner',owner,{bookingId:id},{status:'confirmed'});
    assert.equal(result.status,200);
    result=await call('POST /api/bookings/:id/reschedule','customer',customer,{id},{appointmentAt:'2099-01-02 10:00:00',reason:'Schedule changed'});
    assert.equal(result.status,200);
    const [before]=await db.execute("SELECT DATE_FORMAT(appointment_at,'%Y-%m-%d %H:%i:00') AS slot FROM bookings WHERE id=?",[id]);
    assert.equal(before[0].slot,'2099-01-01 09:00:00');
    result=await call('POST /api/bookings/:id/reschedule','customer',customer,{id},{appointmentAt:'2099-01-03 10:00:00',reason:'Duplicate request'});
    assert.equal(result.status,409);
    result=await call('PATCH /api/owner/bookings/:id/reschedule','owner',owner,{id},{status:'approved'});
    assert.equal(result.status,200);
    const [after]=await db.execute("SELECT DATE_FORMAT(b.appointment_at,'%Y-%m-%d %H:%i:00') AS slot, dp.status FROM bookings b JOIN booking_deposits dp ON dp.booking_id=b.id WHERE b.id=?",[id]);
    assert.equal(after[0].slot,'2099-01-02 10:00:00');assert.equal(after[0].status,'verified');
    result=await call('POST /api/bookings','customer',customer,{}, {serviceId:service,appointmentAt:'2099-01-02 10:30:00'});
    assert.equal(result.status,409);
    // A pending booking created before deposits existed must accept proof too.
    const legacyId = await insert('INSERT INTO bookings(user_id,service_id,appointment_at) VALUES (?,?,?)', [customer,service,'2099-01-04 09:00:00']);
    result=await call('POST /api/bookings/:id/deposit','customer',customer,{id:legacyId},{reference:'9876543210123',imageData:receipt});
    assert.equal(result.status,200);
    const [legacyPayments]=await db.execute('SELECT amount,status FROM booking_deposits WHERE booking_id=?',[legacyId]);
    assert.equal(Number(legacyPayments[0].amount),200);
    assert.equal(legacyPayments[0].status,'submitted');
    const [notifications] = await db.execute('SELECT user_id, title, destination, reference_id FROM notifications WHERE reference_id=? AND user_id IN (?,?)', [id,owner,customer]);
    const hasNotice = (userId, title, destination) => notifications.some(item => Number(item.user_id) === userId && item.title === title && item.destination === destination);
    assert.ok(hasNotice(owner, 'Down payment submitted', 'owner-bookings'));
    assert.ok(hasNotice(customer, 'Payment proof submitted', 'bookings'));
    assert.ok(hasNotice(customer, 'Down payment verified', 'bookings'));
    assert.ok(hasNotice(customer, 'Booking confirmed', 'bookings'));
    result=await call('PATCH /api/owner/bookings/:id/deposit','owner',owner,{id:legacyId},{status:'rejected'});
    assert.equal(result.status,200);
    const [rejections]=await db.execute("SELECT id FROM notifications WHERE user_id=? AND reference_id=? AND title='Payment proof rejected'",[customer,legacyId]);
    assert.equal(rejections.length,1);
    const {processAppointmentReminders,philippineDateTime}=require('../src/services/appointment-reminders');
    const reminderPool={getConnection:async()=>scoped,execute:(sql,args)=>db.execute(sql.replace("WHERE b.status='confirmed'", "WHERE b.id=? AND b.status='confirmed'"),[id,...args])};
    await processAppointmentReminders(reminderPool,new Date('2099-01-02T09:45:00+08:00'));
    await processAppointmentReminders(reminderPool,new Date('2099-01-02T09:46:00+08:00'));
    await processAppointmentReminders(reminderPool,new Date('2099-01-02T10:00:00+08:00'));
    const [reminders]=await db.execute("SELECT title FROM notifications WHERE user_id=? AND reference_id=? AND title IN ('Appointment in 15 minutes','Your appointment starts now')",[customer,id]);
    assert.equal(reminders.length,2);
    await processAppointmentReminders(reminderPool,new Date('2099-01-02T10:14:59+08:00'));
    const [notLate]=await db.execute('SELECT status FROM bookings WHERE id=?',[id]);
    assert.equal(notLate[0].status,'confirmed');
    await processAppointmentReminders(reminderPool,new Date('2099-01-02T10:15:00+08:00'));
    await processAppointmentReminders(reminderPool,new Date('2099-01-02T10:16:00+08:00'));
    const [missed]=await db.execute('SELECT status FROM bookings WHERE id=?',[id]);
    assert.equal(missed[0].status,'cancelled');
    const [cancellations]=await db.execute("SELECT id FROM notifications WHERE user_id=? AND reference_id=? AND title LIKE 'Appointment cancelled%'",[customer,id]);
    assert.equal(cancellations.length,1);
    result=await call('POST /api/bookings/:id/reschedule','customer',customer,{id},{appointmentAt:'2099-01-05 09:00:00',reason:'Missed appointment'});
    assert.equal(result.status,200);
    result=await call('PATCH /api/owner/bookings/:id/reschedule','owner',owner,{id},{status:'approved'});
    assert.equal(result.status,200);
    const [restored]=await db.execute('SELECT b.status,dp.status AS deposit FROM bookings b JOIN booking_deposits dp ON dp.booking_id=b.id WHERE b.id=?',[id]);
    assert.equal(restored[0].status,'confirmed');assert.equal(restored[0].deposit,'verified');
    const nearSlot=philippineDateTime(new Date(Date.now()+5*60000)).slice(0,16)+':00';
    await db.execute('UPDATE bookings SET appointment_at=? WHERE id=?',[nearSlot,id]);
    result=await call('PATCH /api/owner/bookings/:id/arrival','owner',customer,{id},{});
    assert.equal(result.status,404);
    result=await call('PATCH /api/owner/bookings/:id/arrival','owner',owner,{id},{});
    assert.equal(result.status,200);
    await processAppointmentReminders(reminderPool,new Date(Date.now()+21*60000));
    const [arrived]=await db.execute('SELECT status FROM bookings WHERE id=?',[id]);
    assert.equal(arrived[0].status,'confirmed');
    const staffUser=await user('stylist');
    const staffId=await insert('INSERT INTO stylists(user_id,salon_id,is_available) VALUES (?,?,TRUE)',[staffUser,salon]);
    result=await call('POST /api/bookings','customer',customer,{}, {serviceId:service,stylistId:staffId,appointmentAt:'2099-02-01 09:00:00'});
    const occupiedId=result.data.id;
    await db.execute("UPDATE booking_deposits SET status='verified' WHERE booking_id=?",[occupiedId]);
    result=await call('PATCH /api/owner/bookings/:bookingId','owner',owner,{bookingId:occupiedId},{status:'confirmed'});
    assert.equal(result.status,200);
    result=await call('POST /api/bookings','customer',customer,{}, {serviceId:service,stylistId:staffId,appointmentAt:'2099-02-01 09:00:00',joinQueue:true});
    assert.equal(result.status,200);assert.equal(result.data.isQueued,true);
    const queuedId=result.data.id;
    await db.execute("UPDATE booking_deposits SET status='verified' WHERE booking_id=?",[queuedId]);
    result=await call('POST /api/bookings','customer',customer,{}, {serviceId:service,stylistId:staffId,appointmentAt:'2099-02-01 09:00:00',joinQueue:true});
    const secondQueuedId=result.data.id;
    await db.execute("UPDATE booking_deposits SET status='verified' WHERE booking_id=?",[secondQueuedId]);
    result=await call('PATCH /api/owner/bookings/:bookingId','owner',owner,{bookingId:queuedId},{status:'confirmed'});
    assert.equal(result.status,409);
    result=await call('PATCH /api/owner/bookings/:bookingId','owner',owner,{bookingId:occupiedId},{status:'completed'});
    assert.equal(result.status,200);
    result=await call('PATCH /api/owner/bookings/:bookingId','owner',owner,{bookingId:secondQueuedId},{status:'confirmed'});
    assert.equal(result.status,409);
    result=await call('PATCH /api/owner/bookings/:bookingId','owner',owner,{bookingId:queuedId},{status:'confirmed'});
    assert.equal(result.status,200);
    const [queueRows]=await db.execute('SELECT booking_id FROM booking_queue WHERE booking_id=?',[queuedId]);
    assert.equal(queueRows.length,0);



  } finally { await db.rollback(); db.release(); await pool.end(); }
});
