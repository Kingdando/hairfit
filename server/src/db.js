const { Pool } = require('pg');

if (!process.env.SUPABASE_DB_URL) {
  throw new Error('SUPABASE_DB_URL is missing from the server environment.');
}

function replaceQuestionMarks(sql) {
  let index = 0;
  let quote = null;
  let output = '';
  for (let cursor = 0; cursor < sql.length; cursor += 1) {
    const character = sql[cursor];
    if (quote) {
      output += character;
      if (character === quote && sql[cursor - 1] !== '\\') quote = null;
      continue;
    }
    if (character === "'" || character === '"') { quote = character; output += character; }
    else if (character === '?') { index += 1; output += `$${index}`; }
    else output += character;
  }
  return output;
}

function translateSql(sql) {
  const ignoreInsert = /INSERT\s+IGNORE\s+INTO/i.test(sql);
  let translated = sql
    .replace(/`([^`]+)`/g, '"$1"')
    .replace(/BIGINT\s+UNSIGNED\s+AUTO_INCREMENT/gi, 'BIGINT GENERATED BY DEFAULT AS IDENTITY')
    .replace(/BIGINT\s+UNSIGNED/gi, 'BIGINT')
    .replace(/TINYINT\s+UNSIGNED/gi, 'SMALLINT')
    .replace(/MEDIUMTEXT/gi, 'TEXT')
    .replace(/DATETIME/gi, 'TIMESTAMP')
    .replace(/DATE_FORMAT\(([^,]+),\s*'%Y-%m-%d %H:%i:%s'\)/gi, "to_char($1, 'YYYY-MM-DD HH24:MI:SS')")
    .replace(/DATE_FORMAT\(([^,]+),\s*'%Y-%m-%d %H:%i:00'\)/gi, "to_char($1, 'YYYY-MM-DD HH24:MI:00')")
    .replace(/UTC_TIMESTAMP\(\)/gi, "(CURRENT_TIMESTAMP AT TIME ZONE 'UTC')")
    .replace(/DATE_ADD\(([^,]+),\s*INTERVAL\s+([^\s)]+)\s+(MINUTE|HOUR|DAY)\)/gi, "(($1)::timestamp + ($2 * INTERVAL '1 $3'))")
    .replace(/DATE_SUB\(([^,]+),\s*INTERVAL\s+([^\s)]+)\s+(MINUTE|HOUR|DAY)\)/gi, "(($1)::timestamp - ($2 * INTERVAL '1 $3'))")
    .replace(/SUBSTRING_INDEX\(TRIM\(([^)]+)\),\s*' ',\s*1\)/gi, "split_part(trim($1), ' ', 1)")
    .replace(/INSERT\s+IGNORE\s+INTO/gi, 'INSERT INTO')
    .replace(/\s+ON DUPLICATE KEY UPDATE\s+hair_type\s*=\s*VALUES\(hair_type\),\s*hair_length\s*=\s*VALUES\(hair_length\),\s*hair_texture\s*=\s*VALUES\(hair_texture\)/gi,
      ' ON CONFLICT (user_id) DO UPDATE SET hair_type = EXCLUDED.hair_type, hair_length = EXCLUDED.hair_length, hair_texture = EXCLUDED.hair_texture')
    .replace(/\s+ON DUPLICATE KEY UPDATE\s+notifications_enabled\s*=\s*VALUES\(notifications_enabled\),\s*save_scan_history\s*=\s*VALUES\(save_scan_history\)/gi,
      ' ON CONFLICT (user_id) DO UPDATE SET notifications_enabled = EXCLUDED.notifications_enabled, save_scan_history = EXCLUDED.save_scan_history');
  translated = translated.replace(/\s+ON DUPLICATE KEY UPDATE\s+([^;]+)/gi, (_, body) => {
    const normalized = body.trim().replace(/\s+/g, '').toLowerCase();
    if (normalized === 'id=id') return ' ON CONFLICT DO NOTHING';
    const updates = body.replace(/\bVALUES\((\w+)\)/gi, 'EXCLUDED.$1');
    return ` ON CONFLICT DO UPDATE SET ${updates}`;
  });
  translated = translated.replace(/IF\(r\.comment IS NULL OR r\.comment = '',\s*'',\s*CONCAT\(' · ', r\.comment\)\)/gi, "CASE WHEN r.comment IS NULL OR r.comment = '' THEN '' ELSE CONCAT(' · ', r.comment) END");
  translated = translated.replace(/IF\(([^(),]+),\s*([^(),]+),\s*([^()]+)\)/gi, 'CASE WHEN $1 THEN $2 ELSE $3 END');
  if (ignoreInsert && !/\bON CONFLICT\b/i.test(translated)) translated = `${translated} ON CONFLICT DO NOTHING`;
  return replaceQuestionMarks(translated);
}

const returningTables = new Set(['users', 'salons', 'stylists', 'services', 'bookings', 'face_analyses', 'saved_hairstyles', 'notifications', 'reviews', 'salon_portfolio_images', 'review_replies', 'booking_changes', 'stylist_portfolio']);
function addReturning(sql) {
  if (!/^\s*INSERT\s+INTO\s+/i.test(sql) || /\bRETURNING\b/i.test(sql) || /\bSELECT\b/i.test(sql)) return sql;
  const match = sql.match(/^\s*INSERT\s+INTO\s+([a-z_]+)/i);
  return match && returningTables.has(match[1].toLowerCase()) ? `${sql} RETURNING id` : sql;
}
function postgresResult(result) {
  const rows = result.rows || [];
  if (result.command === 'SELECT') return [rows, undefined];
  return [{
    affectedRows: result.rowCount || 0,
    insertId: result.command === 'INSERT' && rows[0]?.id != null ? Number(rows[0].id) : undefined,
  }, undefined];
}
function makePostgresClient(client) {
  return {
    async execute(sql, values = []) { return postgresResult(await client.query(addReturning(translateSql(sql)), values)); },
    async query(sql, values = []) { return client.query(translateSql(sql), values); },
    async beginTransaction() { await client.query('BEGIN'); },
    async commit() { await client.query('COMMIT'); },
    async rollback() { await client.query('ROLLBACK'); },
    release() { client.release(); },
  };
}
const pool = new Pool({ connectionString: process.env.SUPABASE_DB_URL, ssl: process.env.SUPABASE_DB_SSL === 'false' ? false : { rejectUnauthorized: false }, max: Number(process.env.DB_POOL_SIZE || 10) });
module.exports = {
  dialect: 'postgres',
  async execute(sql, values = []) { return postgresResult(await pool.query(addReturning(translateSql(sql)), values)); },
  async query(sql, values = []) { return pool.query(translateSql(sql), values); },
  async getConnection() { return makePostgresClient(await pool.connect()); },
  async end() { await pool.end(); },
  postgresResult,
};
